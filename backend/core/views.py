# ── POST /api/classes/join/ ───────────────────────────────────────────────────

class JoinClassView(APIView):
    """
    Public — no auth required.

    Join-code auth flow (ARCHITECTURE.md):
      • Nickname not in class  → create Student, issue device_token.
      • Nickname exists + PIN matches → rotate device_token (new-device re-entry).
      • Nickname exists + PIN wrong  → 401.
    """

    authentication_classes = []
    permission_classes     = []

    def post(self, request):
        ser = JoinClassSerializer(data=request.data)
        ser.is_valid(raise_exception=True)

        join_code = ser.validated_data['join_code'].strip().upper()
        nickname  = ser.validated_data['nickname']   # stripped by serializer validator
        pin       = ser.validated_data['pin']

        school_class = get_object_or_404(
            SchoolClass.objects.select_related('school', 'subject'),
            join_code=join_code,
        )

        try:
            student = Student.objects.get(
                school_class=school_class,
                nickname__iexact=nickname,
            )
        except Student.DoesNotExist:
            student = Student.objects.create(
                school_class=school_class,
                nickname=nickname,
                pin=pin,
                # device_token auto-generated by model default (uuid.uuid4)
            )
        else:
            # Nickname already in this class — gate re-entry on correct PIN
            if student.pin != pin:
                return Response(
                    {'error': 'Incorrect PIN. Ask your teacher if you have forgotten it.'},
                    status=status.HTTP_401_UNAUTHORIZED,
                )
            # Rotate token: old device's cached token is immediately invalidated
            student.device_token = uuid.uuid4()
            student.save(update_fields=['device_token'])

        return Response({
            'device_token': str(student.device_token),
            'student_id':   student.id,
            'nickname':     student.nickname,
            'class_name':   school_class.name,
            'subject_id':   school_class.subject_id,
        })


# ── GET /api/units/ ───────────────────────────────────────────────────────────

class UnitListView(StudentAuthMixin, generics.ListAPIView):
    """
    Units for the student's subject with locked state + boss config.
    One extra query fetches all Progress rows up front so is_locked is
    computed without per-unit DB hits.
    """

    serializer_class = UnitSerializer

    def get_queryset(self):
        return (
            Unit.objects
            .filter(subject=self.request.user.school_class.subject)
            .select_related('boss')
            .order_by('order')
        )

    def get_serializer_context(self):
        ctx = super().get_serializer_context()
        ctx['progress_map'] = {
            p.unit_id: p
            for p in Progress.objects.filter(student=self.request.user)
        }
        return ctx


